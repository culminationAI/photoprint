#!/bin/bash
# Установщик клиента «Печать картинок» (спецификация § 4.8).
#
# Запуск — только командой из README, как ставился клиент ресепшена:
#   curl -fsSL https://raw.githubusercontent.com/culminationAI/photoprint/main/install.sh | bash
# Скрипт приходит в bash через stdin, поэтому не попадает под карантин и не
# требует прав на исполнение.
#
# Что делает:
# - кладёт код клиента в `~/.photoprint/app`, окружение Python — в
#   `~/.photoprint/venv` (Корень, § 3.3): тяжёлое лежит вне Рабочего стола;
# - создаёт папку `~/Desktop/Печать картинок` или берёт папку, которую
#   заказчик перенёс (её путь клиент записал в `~/.photoprint/folder`), и
#   кладёт в неё ярлык `Печать картинок.command`;
# - проверяет, что загружается библиотека USB, и говорит, найден ли принтер;
# - повторный запуск той же командой обновляет код, окружение и ярлык.
#
# Окружение (подмены для тестов, § 7.2–7.3):
# - `PHOTOPRINT_TARBALL` — адрес архива вместо GitHub (I3);
# - `PHOTOPRINT_PYTHON` — Python вместо `/usr/bin/python3` (I2);
# - `PHOTOPRINT_SKIP_PIP=1` — без установки зависимостей (I6) и без
#   проверки принтера (I8).
# Все свои сообщения скрипт печатает в stdout; причину сбоя печатает в
# stderr сама упавшая команда (I10).
#
# Правила спецификации, которые держит скрипт:
# - I1 — ставится в `$HOME/.photoprint`, текущий каталог не трогается;
#   папка — записанная клиентом, если такой каталог есть, иначе
#   `~/Desktop/Печать картинок`;
# - I2 — Python 3.9 или новее; для `/usr/bin/python3` — сначала
#   инструменты разработчика Apple;
# - I3–I8 — шаги «скачивание», «замена кода», «окружение», «зависимости»,
#   «папка и ярлык», «библиотека USB»;
# - I9 — «Готово…» с путём папки, код 0;
# - I10 — перед каждым шагом строка «▸ …»; сбой шага — текст с его именем;
#   временный каталог убирается и при успехе, и при сбое;
# - I11 — обновление той же командой; в папке меняется только ярлык;
# - I12 — только конструкции bash 3.2.
#
# `#!/bin/bash` — на маке это bash 3.2: только его конструкции (I12).
# Переменная прямо перед русским текстом — только `${имя}` (см. `on_exit`).
# Весь код — в функциях, последняя строка файла — вызов `main` (§ 4.8):
# если скачивание скрипта оборвалось посередине, строки вызова нет, и bash
# ничего не исполняет. Выше неё вне функций — только `set` и присваивания
# трёх глобальных: они ничего не создают и не печатают.

# I10: любая упавшая команда прерывает установку (`-e`), опечатка в имени
# переменной — тоже (`-u`), сбой в любом звене конвейера не теряется
# (`pipefail`).
# Но bash 3.2, оборвав скрипт на незаданной переменной («unbound
# variable»), выходит с кодом 0: обработчик `EXIT` (`on_exit`) видит `$?`
# = 0, и установка молча кончается кодом 0 — без «Готово…» и без текста
# сбоя I10 (проверено). Поэтому переменные `PHOTOPRINT_*`, которых у
# заказчика нет, читаются только через `${…:-}`, и тесты гоняют
# установщик и без них: без `PHOTOPRINT_SKIP_PIP` —
# `test_install_deps_without_skip_pip_variable` (pip и проверка принтера
# вызваны), без `PHOTOPRINT_PYTHON` — все тесты, которые не подменяют
# Python (`run_install` его не задаёт), а адрес по умолчанию
# `${PHOTOPRINT_TARBALL:-…}` сверяется по тексту (`test_install_default_url`).
set -euo pipefail

# I10: глобальные, а не `local`: их читает `on_exit`, который bash вызывает
# при выходе из скрипта — в том числе посреди любой функции шага. `STEP` —
# имя идущего шага (пусто — вне шагов), `TMP` — временный каталог
# скачивания (пусто — ещё не создан).
STEP=""
TMP=""
# I1: Корень клиента (§ 3.3).
R="$HOME/.photoprint"

# I10: обработчик выхода (`trap on_exit EXIT`). Выполняется при любом
# выходе — успех, сбой команды под `set -e`, `exit 1` шага, Ctrl+C.
# Убирает временный каталог и, если упал шаг, говорит заказчику, какой и
# что делать; код выхода остаётся прежним.
on_exit() {
  # Первой строкой: любая команда до неё затёрла бы код выхода.
  rc=$?
  [ -z "$TMP" ] || rm -rf "$TMP"
  if [ "$rc" -ne 0 ] && [ -n "$STEP" ]; then
    # I12: `${STEP}` в фигурных скобках: в локали UTF-8 bash 3.2 на маке
    # считает первый байт закрывающей кавычки `»` частью имени переменной,
    # и `$STEP` без скобок прямо перед `»` под `set -u` роняет обработчик с
    # «unbound variable» (проверено) — текст сбоя не дошёл бы до заказчика.
    echo "Установка не удалась на шаге «${STEP}». Причина — в сообщениях выше. Выполните команду установки ещё раз."
    if [ "$STEP" = "папка и ярлык" ]; then
      # I10: на этом шаге macOS отказывает с «Operation not permitted», если
      # Терминалу не дали доступ к Рабочему столу.
      echo "Если выше «Operation not permitted» — разрешите Терминалу доступ к Рабочему столу: Системные настройки → Конфиденциальность и безопасность → Файлы и папки → Терминал."
    fi
  fi
  exit "$rc"
}

# I2: проверить Python, на котором будет окружение клиента. Не прошёл —
# свой текст и код 1. `STEP` ещё пуст, поэтому текста сбоя шага нет, и
# ничего не создано: `.photoprint` появляется только после I2.
check_python() {
  # Глобальная: ею же шаг «окружение» создаёт venv (I5).
  PY="${PHOTOPRINT_PYTHON:-/usr/bin/python3}"
  if [ "$PY" = /usr/bin/python3 ]; then
    # I2: без Command Line Tools `/usr/bin/python3` — заглушка, которая
    # открывает окно установки, поэтому для проверки её не вызываем, а
    # ищем настоящий python3 инструментов: на стандартном месте или в
    # каталоге, который выбран `xcode-select`. `-x`, а не код выхода
    # `xcode-select -p`: он возвращает 0 и для несуществующего пути.
    local DEV
    DEV="$(xcode-select -p 2>/dev/null || true)"
    local tools=no
    if [ -x /Library/Developer/CommandLineTools/usr/bin/python3 ] || { [ -n "$DEV" ] && [ -x "$DEV/usr/bin/python3" ]; }; then
      tools=yes
    fi
    if [ "$tools" = no ]; then
      # I2: окно установки инструментов открываем сами — заказчику
      # остаётся нажать «Установить». Отказ `xcode-select` (например, окно
      # уже открыто) не мешает напечатать текст.
      xcode-select --install >/dev/null 2>&1 || true
      echo "Нужны инструменты разработчика Apple. В открывшемся окне нажмите «Установить» (не «Получить Xcode»), при запросе введите пароль от мака и дождитесь конца — 10–30 минут. Потом выполните команду установки ещё раз."
      exit 1
    fi
  fi
  if ! "$PY" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)'; then
    echo "Нужен Python 3.9 или новее."
    exit 1
  fi
}

# I1: выбрать папку для картинок `F` (глобальная: её читают шаг «папка и
# ярлык» и «Готово…»). Клиент при каждом запуске пишет путь своей папки в
# `$R/folder` (M4) — так обновление находит папку, которую заказчик
# перенёс. Файла нет, он пуст или каталога по нему уже нет — папка по
# умолчанию на Рабочем столе; удалённый каталог не воскрешается.
choose_folder() {
  # Пусто, пока не прочитано: под `set -u` проверка ниже иначе упала бы.
  F=""
  if [ -f "$R/folder" ]; then
    F="$(cat "$R/folder")"
  fi
  if [ -z "$F" ] || [ ! -d "$F" ]; then
    F="$HOME/Desktop/Печать картинок"
  fi
}

# I3: скачать архив ветки `main` во временный каталог внутри Корня и
# распаковать его без верхнего каталога (`photoprint-main/`).
step_download() {
  # I3: адрес архива; тесты подставляют `file://` на свой архив (§ 7.2).
  local URL="${PHOTOPRINT_TARBALL:-https://codeload.github.com/culminationAI/photoprint/tar.gz/refs/heads/main}"
  # I3: временный каталог — в Корне, а не в системной временной папке:
  # `mv` кода в I4 тогда — переименование на том же диске. Убирает его
  # `on_exit` (I10).
  TMP="$(mktemp -d "$R/tmp.XXXXXX")"
  mkdir "$TMP/src"
  # I3: в файл, а не конвейером в `tar`: bsdtar возвращает 0 на пустом
  # входе, и несостоявшееся скачивание прошло бы молча. `-S` оставляет
  # текст ошибки curl в stderr (I10: причину печатает сама команда).
  curl -fsSL --retry 3 -o "$TMP/src.tar.gz" "$URL"
  tar xzf "$TMP/src.tar.gz" --strip-components=1 -C "$TMP/src"
  # I3: архив распаковался, но кода клиента в нём нет — без этой проверки
  # «замена кода» заменила бы рабочий клиент пустым местом.
  if [ ! -f "$TMP/src/app/photoprint/__init__.py" ]; then
    echo "В скачанном архиве нет app/photoprint."
    exit 1
  fi
}

# I4: заменить код клиента целиком. Прежний `app` отодвигается в `app.old`
# и удаляется только после того, как новый встал на место: сбой до этого
# оставляет прежний код целым, а файлы, которых в новой версии нет, не
# остаются.
step_replace_code() {
  # I4 п. 1: остаток прошлой оборванной замены.
  rm -rf app.old
  # I4 п. 2: при первой установке прежнего кода нет.
  if [ -d app ]; then
    mv app app.old
  fi
  # I4 п. 3.
  mv "$TMP/src/app" app
  # Решение контролёра к I4 (трассировка — «иначе: ревью»): libusb с меткой
  # карантина система не загружает, и вся печать дала бы «Не загрузилась
  # библиотека USB». curl и tar карантин не ставят — это страховка на
  # случай доставки архивом через браузер. Файлы без метки `xattr` не
  # меняет, а его отказ установку не прерывает.
  xattr -dr com.apple.quarantine app 2>/dev/null || true
  # I4 п. 4.
  rm -rf app.old
}

# I5: окружение Python. Рабочее — python запускается, в нём есть pip и
# метка `venv/.photoprint-arch` называет архитектуру этого запуска —
# остаётся как есть: повторная установка его не пересоздаёт. Иначе оно
# удаляется и создаётся заново: после переустановки Command Line Tools с
# другой версией Python `venv/bin/python` — висячая ссылка или Python без
# своих пакетов.
step_venv() {
  # I10: результат проверки — в переменную через `if` вокруг самих
  # проверок. `set -e` не действует только в условии `if`; обёрнутый в
  # `if` шаг целиком потерял бы его для всех своих команд. Вывод проверки не
  # нужен: для висячей ссылки bash напечатал бы «No such file or
  # directory», хотя это не сбой, а повод создать окружение заново.
  # I5: метка архитектуры — потому что окружение, перенесённое с Intel-мака
  # Ассистентом миграции или созданное в Терминале под Rosetta, проходит
  # `import pip`, pip считает пакеты установленными, а Pillow и
  # pydantic-core под другой архитектурой не загружаются: без метки
  # повторная установка такое окружение не чинила бы. `cat` метки — с
  # `2>/dev/null`: у окружения от прежней версии установщика метки нет, и
  # это тоже повод создать его заново, а не текст ошибки для заказчика.
  local healthy=no
  if venv/bin/python -c 'import pip' >/dev/null 2>&1 && [ "$(cat venv/.photoprint-arch 2>/dev/null)" = "$(uname -m)" ]; then
    healthy=yes
  fi
  if [ "$healthy" = no ]; then
    rm -rf venv
    "$PY" -m venv venv
    # I5: метка — после создания окружения: оборванное создание оставляет
    # окружение без метки, и следующая установка создаст его заново.
    uname -m > venv/.photoprint-arch
  fi
}

# I6: зависимости клиента — только колёсами; pip из venv не обновляется,
# его хватает (§ 8). `PHOTOPRINT_SKIP_PIP=1` пропускает шаг уже после его
# строки «▸ …»: тесты не качают пакеты (§ 7.2).
step_deps() {
  if [ "${PHOTOPRINT_SKIP_PIP:-}" = 1 ]; then
    return 0
  fi
  venv/bin/python -m pip install --disable-pip-version-check --quiet --only-binary=:all: -r app/requirements.txt
}

# I7, I11: папка для картинок и ярлык в ней. В папке меняется только
# ярлык: картинки и `.print-stats.json` не трогаются.
step_folder() {
  mkdir -p "$F"
  # I7: прежний ярлык — удалить, чтобы ниже `cat` создал новый файл: `>` в
  # существующий файл сохраняет его расширенные атрибуты, и ярлык с меткой
  # карантина (папка пришла через AirDrop, мессенджер или архив из
  # браузера) остался бы заблокирован Gatekeeper и после переустановки.
  # I7: сначала снять флаг `uchg` — галочку «Защита» в свойствах ярлыка в
  # Finder. С ним `rm -f` падает с «Operation not permitted», и подсказка
  # I10 про доступ к Рабочему столу увела бы заказчика не туда: доступ у
  # Терминала есть, а повтор команды падал бы так же (финальная проверка,
  # 2026-09-28). Отказ `chflags` установку не прерывает: при первой
  # установке ярлыка ещё нет. Если нет доступа к Рабочему столу, о нём
  # скажет `rm -f` ниже — и подсказка тогда верна.
  chflags nouchg "$F/Печать картинок.command" 2>/dev/null || true
  rm -f "$F/Печать картинок.command"
  # I7: именно `cat` в файл: `cp` и `mv` перенесли бы атрибут карантина, а
  # созданный так файл открывается двойным щелчком без Gatekeeper.
  cat app/launcher.command > "$F/Печать картинок.command"
  chmod 755 "$F/Печать картинок.command"
}

# I8: библиотека USB и принтер — проверка самого клиента (M6): python
# окружения запускается из каталога кода, где `-m photoprint` находит
# пакет, как у ярлыка (L3). Код 1 — libusb не загрузилась, и печать
# работать не будет: под `set -e` это сбой шага. «Принтер не найден» —
# код 0: принтер подключат потом, клиент всё равно установлен. Вывод
# проверки не глушится — ни stdout, ни stderr: по нему заказчик узнаёт,
# найден ли принтер, и он же — причина сбоя, на которую ссылается текст
# I10 «Причина — в сообщениях выше». Если клиент упал ещё на импорте
# (колёса не под ту архитектуру), его трассировка в stderr — единственная
# причина. Круглые скобки — `cd` только внутри них: текущий каталог
# установки остаётся Корнем.
step_usb() {
  # I8, § 7.3: `./app`, а не `app` — путь с `./` bash не ищет в `CDPATH`.
  # Заказчик может экспортировать `CDPATH` из `~/.zshrc`: тогда `cd app`
  # ушёл бы в чужой `<каталог из CDPATH>/app`, где нет `../venv`, и шаг
  # падал бы при каждой установке, а при `CDPATH=.:…` печатал бы лишней
  # строкой путь каталога. Ярлык защищён от `CDPATH` так же (L1).
  (cd ./app && ../venv/bin/python -m photoprint --check-printer)
}

# Установка по шагам I1–I10. Каждый шаг — функция, вызванная простой
# командой после `STEP=` и строки «▸ …» (I10): не из `if`, `||`, `&&`, `!`
# и не внутри `local x=$(…)` — там `set -e` не действует, и упавший шаг
# прошёл бы молча. Так установка прерывается на первой же ошибке шага, а
# `on_exit` знает, какой шаг упал.
main() {
  # I10: обработчик выхода — первым, до любой команды, которая может упасть.
  trap on_exit EXIT
  # I1: stdin — это сам скрипт (`curl … | bash`); дочерние команды не
  # должны прочитать из него строки, которые bash ещё не исполнил.
  exec </dev/null

  check_python
  choose_folder
  # I1: дальше всё — в Корне: относительные пути I3–I8 считаются от него, а
  # текущий каталог заказчика не трогается.
  mkdir -p "$R"
  cd "$R"

  # I3: скачать и распаковать архив во временный каталог.
  STEP="скачивание"
  echo "▸ скачивание…"
  step_download

  # I4: заменить код клиента целиком.
  STEP="замена кода"
  echo "▸ замена кода…"
  step_replace_code

  # I5: оставить рабочее окружение Python или создать его заново.
  STEP="окружение"
  echo "▸ окружение…"
  step_venv

  # I6: поставить зависимости; строка шага печатается и при пропуске.
  STEP="зависимости"
  echo "▸ зависимости — это может занять несколько минут…"
  step_deps

  # I7: папка для картинок и ярлык в ней.
  STEP="папка и ярлык"
  echo "▸ папка и ярлык…"
  step_folder

  # I8: библиотека USB и принтер. Без зависимостей
  # (`PHOTOPRINT_SKIP_PIP=1`) в окружении нет ни escpos, ни pyusb, и
  # проверять нечем: шаг пропускается целиком — без `STEP=` и без строки
  # «▸ …», в отличие от «зависимостей». Шаг — в теле `if`, а не в его
  # условии, поэтому `set -e` в нём действует (I10).
  if [ "${PHOTOPRINT_SKIP_PIP:-}" != 1 ]; then
    STEP="библиотека USB"
    echo "▸ библиотека USB…"
    step_usb
  fi

  # I9: шаги кончились — выход дальше не сбой шага.
  STEP=""
  # `${F}` в фигурных скобках, как все переменные рядом с русским текстом
  # (см. `on_exit`).
  echo "Готово. Папка для картинок: ${F}. Положите в неё JPEG и дважды щёлкните «Печать картинок». Если окно «Печать картинок» было открыто — закройте его и откройте снова."
}

# § 4.8: вызов `main` — последняя строка файла, её нет в оборванном
# скрипте. `exit` на той же строке: bash завершается сразу после `main` и
# больше ничего из stdin не читает.
main "$@"; exit
