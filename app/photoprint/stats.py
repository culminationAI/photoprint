"""Счётчики печати: сколько раз каждая картинка напечаталась и сколько раз сорвалась.

Счёт хранится в самой папке с картинками, в скрытом файле `.print-stats.json`,
и переезжает вместе с ней (спецификация § 4.2). Это обычный JSON: его можно
открыть и поправить руками, и работающий клиент правку увидит.

Правила спецификации, которые держит модуль:
- S1 — нет файла, записи или поля — ноль; файл создаёт только первый
  `increment`; поле не из `FIELDS` — `ValueError` до любой работы с файлом;
- S2 — каждая операция читает файл заново в UTF-8, в памяти ничего не
  хранится;
- S3 — `increment` читает, прибавляет и пишет под одним замком, а файл
  заменяется атомарно: временный файл рядом, `fsync`, права 0644,
  `os.replace`;
- S4 — битый файл (не UTF-8, не JSON, вложенность глубже предела рекурсии,
  ключ, повторённый в одном объекте, или структура не «имя → запись», где
  имя кодируется в UTF-8, а в записи только поля `FIELDS` с целыми ≥ 0)
  `get` читает как ноль и не трогает, а `increment` откладывает в
  `BROKEN_FILE` и считает с пустого;
- S5 — сбой файловой системы в `increment`, в том числе при переименовании
  битого файла, — `StatsWriteError` с одной причиной, прежний файл цел,
  временный удалён; сбой чтения в `get` — ноль;
- S6 — ключом служит имя картинки ровно как в `os.listdir`, без
  нормализации Unicode: переименованная картинка считается с нуля, записи
  удалённых картинок остаются в файле.

Для списка картинок (W1) — `snapshot`: счёт всех картинок из одного чтения
файла по тем же правилам, что `get` (финальная проверка, 2026-09-28);
`get` берёт его же.
"""
from __future__ import annotations

import json
import os
import tempfile
import threading
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple

# S6: файл счётчиков лежит в папке с картинками и переезжает вместе с ней.
# Имя скрытое, поэтому в список картинок он не попадает (F1).
STATS_FILE = ".print-stats.json"
# S4: сюда `increment` откладывает битый файл счётчиков, а прежняя
# отложенная копия заменяется. Имя тоже скрытое (F1).
BROKEN_FILE = ".print-stats.broken.json"
# Поля записи: напечатано и сбоев. Имена совпадают с полями `Counts`, поэтому
# запись с обоими полями превращается в `Counts(**record)`.
FIELDS = ("printed", "failed")


@dataclass(frozen=True)
class Counts:
    """Счёт одной картинки: сколько раз напечатана и сколько раз печать сорвалась.

    Неизменяемый: это снимок файла на момент чтения, а не живой счётчик —
    следующая операция всё равно прочтёт файл заново (S2).
    """

    printed: int
    failed: int


class StatsWriteError(OSError):
    """Счёт не удалось прочитать или записать; `str(exc)` — ровно причина.

    Причина — `strerror` исходной ошибки, например «Permission denied»: её
    покажет страница (S5). Исходная ошибка лежит в `__cause__`.
    """


def _unique_object(pairs: List[Tuple[str, object]]) -> Dict[str, object]:
    """Собрать объект JSON из пар «ключ — значение»; ключ повторён — `ValueError` (S4).

    Это `object_pairs_hook` для `json.loads`: разборщик зовёт его для
    каждого объекта файла — и для корня, и для каждой записи, — поэтому
    повтор отвергается на любом уровне. Порядок пар сохраняется, как у
    `json.loads` без хука.
    """
    obj = dict(pairs)
    # S4 (решение контролёра по задаче 2.2): ключ, повторённый в одном
    # объекте, — битый файл. Так бывает после правки руками: запись или
    # поле вписали ещё раз. `json.loads` сам молча оставил бы последнее
    # значение: `get` показал бы счёт одной из двух записей, а следующий
    # `increment` переписал бы файл без другой — и она пропала бы без копии
    # в `BROKEN_FILE`. Повтор виден только здесь, в парах: `object_hook`
    # получает уже готовый `dict`, где повтор схлопнут, а `_valid` — весь
    # разобранный файл.
    # S4: сравниваются длины, а не соседние пары и не первый или последний
    # ключ: по алфавиту ключи пишет только `_write` (`sort_keys=True`), а
    # правка руками вставляет повтор куда угодно — через другие записи.
    if len(obj) != len(pairs):
        # S4: `ValueError` — тот же путь, что у `JSONDecodeError`: хук
        # вызывается внутри `json.loads`, исключение выходит из него как
        # есть, и `_read` отвечает на него «файл битый». Отдельный признак
        # в данных не нужен.
        raise ValueError("duplicate key in stats file")
    return obj


def _valid(data: object) -> bool:
    """Проверить, что разобранный файл счётчиков имеет структуру § 4.2 (S4).

    Корень — объект «имя → запись», ключи — строки, которые кодируются в
    UTF-8, каждая запись — объект, в котором только поля из `FIELDS`, а
    каждое значение — целое ≥ 0. Любое отступление хотя бы в одной записи
    делает битым весь файл.
    """
    # S4: структура — свойство всего файла, а не одной записи. Иначе `get`
    # показывал бы счёт по файлу, который `increment` отложит, а
    # `increment`, переписывая файл целиком, молча потерял бы плохую запись
    # вместо того, чтобы сохранить её в `BROKEN_FILE`.
    # S1, S4: пустой корень `{}` (счёт, сброшенный руками) и пустая запись
    # `{}` (недостающее поле — 0) — правильная структура, а не битый файл.
    # Если бы они считались битыми, следующая печать отложила бы такой файл
    # в `BROKEN_FILE` и затёрла бы прежнюю отложенную копию.
    if not isinstance(data, dict):
        return False
    # S4: проверяются все записи до конца, без выхода после первой:
    # `json.loads` сохраняет порядок файла, и плохая запись может стоять
    # где угодно.
    for name, record in data.items():
        # S4: ключи объекта JSON — всегда строки, но правило требует строку
        # явно, и проверка не полагается на то, как данные получены.
        if not isinstance(name, str) or not isinstance(record, dict):
            return False
        # S4 (решение контролёра по задаче 2.2): экранирование `\udXXX` в
        # JSON даёт `str` с одиноким суррогатом. Проверка типа его
        # пропускает, но в UTF-8 такой ключ не кодируется: `_write` падал
        # бы на нём с `UnicodeEncodeError` при каждой печати, файл не
        # откладывался бы, и счёт больше никогда не сохранялся бы. Поэтому
        # такой ключ — нарушение структуры: `get` читает файл как ноль, а
        # `increment` откладывает его в `BROKEN_FILE`. Имя из `os.listdir`
        # таким не бывает — APFS не принимает имён не в UTF-8.
        # Кодирование — ровно то же, что в `_write`: строгий `utf-8` без
        # `errors=`. Не `os.fsencode` и не `surrogateescape`: они пропускают
        # нижние суррогаты U+DC80..U+DCFF, а `_write` на них всё равно падает.
        try:
            name.encode("utf-8")
        except UnicodeEncodeError:
            return False
        for field, value in record.items():
            if field not in FIELDS:
                return False
            # S4: `bool` в Python — подкласс `int`, и `true` без отдельной
            # проверки прошёл бы как 1; правило целым его не считает.
            # Дробное (`1.5`), `null`, строка — тоже не целое.
            if isinstance(value, bool) or not isinstance(value, int) or value < 0:
                return False
    return True


def _full(record: Dict[str, int]) -> Dict[str, int]:
    """Вернуть новую запись с обоими полями `FIELDS`; недостающее поле — 0 (S1)."""
    return {field: record.get(field, 0) for field in FIELDS}


class Stats:
    """Счётчики одной папки — файл `folder / STATS_FILE`.

    Один объект на папку на весь сервер: его замок разводит одновременные
    `increment` из разных запросов (S3). Счёт в памяти не хранится — только
    путь и замок (S2).
    """

    def __init__(self, folder: Path) -> None:
        """Запомнить папку; файл при этом не читается и не создаётся (S1)."""
        self._folder = folder
        self._path = folder / STATS_FILE
        # S3: один замок на объект — чтение, прибавление и запись одного
        # `increment` не перемежаются с другим, и прибавки не теряются.
        self._lock = threading.Lock()

    def _read(self) -> Optional[Dict[str, Dict[str, int]]]:
        """Прочитать и разобрать файл счётчиков с диска (S2); `None` — файл битый (S4).

        Битый — не UTF-8, не JSON, вложенность глубже предела рекурсии, ключ,
        повторённый в одном объекте, или структура не по `_valid`.
        `OSError` не перехватывает: `FileNotFoundError` и прочие сбои
        чтения разбирают `snapshot` и `increment`, каждый по своему правилу
        (S1, S5).
        """
        try:
            # S2: всегда с диска и всегда в UTF-8 — правка руками при
            # работающем клиенте видна следующей операции, а имена с
            # кириллицей читаются одинаково при любой локали Терминала.
            # S4: декодирование строгое — без `errors=`: файл в cp1251 должен
            # дать `UnicodeDecodeError` и уйти в `BROKEN_FILE` байт в байт, а
            # не переписаться с U+FFFD или без букв. И не `utf-8-sig`: метка
            # порядка байт остаётся символом, и `json.loads` считает такой
            # файл битым (`JSONDecodeError`).
            # S4: `_unique_object` собирает каждый объект файла и бросает
            # `ValueError`, если ключ в нём повторён (решение контролёра по
            # задаче 2.2).
            data = json.loads(
                self._path.read_text(encoding="utf-8"), object_pairs_hook=_unique_object
            )
        except (ValueError, RecursionError):
            # S4: не UTF-8 (`UnicodeDecodeError`), не JSON
            # (`JSONDecodeError`) и повтор ключа (`ValueError` из
            # `_unique_object`) — все `ValueError`. `OSError` чтения сюда
            # не попадает: это сбой (S5), а не битый файл, и откладывать
            # такой файл нельзя — в нём, может быть, весь счёт.
            # S4 (решение контролёра по задаче 2.2): вложенность глубже
            # предела рекурсии (`[[[[…` на тысячу уровней) `json.loads`
            # разбирает рекурсивно и бросает `RecursionError` — это
            # `RuntimeError`, а не `ValueError`. Без него `get` и `snapshot`
            # бросали бы и список W1 лежал бы, а `increment` падал бы после
            # печати, не отложив файл, — и перезапуск не помогал бы. Ловится
            # только `RecursionError`, а не весь `RuntimeError`: другой сбой
            # здесь — ошибка кода, а не битый файл.
            return None
        return data if _valid(data) else None

    def _write(self, data: Dict[str, Dict[str, int]]) -> None:
        """Атомарно заменить файл счётчиков содержимым `data` (S3).

        Текст пишется целиком во временный файл рядом и подменяет прежний
        одним `os.replace`: читатель видит либо старый файл, либо новый, но
        не половину. При любом сбое временный файл удаляется, прежний не
        тронут, а исключение уходит выше как есть (S5).
        """
        # § 4.2: отступ 2, ключи по алфавиту, кириллица как есть — файл
        # удобно читать и править руками. Текст собирается до `mkstemp`,
        # чтобы сбой сериализации не оставил временного файла.
        text = json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
        # S3: временный файл в той же папке — `os.replace` атомарен только в
        # пределах одной файловой системы. Имя скрытое (`.print-stats.…tmp`),
        # поэтому остаток после убитого процесса не попадёт в список (F1).
        fd, tmp = tempfile.mkstemp(dir=self._folder, prefix=".print-stats.", suffix=".tmp")
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as stream:
                stream.write(text)
                # S3: `flush` отдаёт буфер Python ядру, `fsync` — ядро диску:
                # к `os.replace` на диске уже полный новый файл, и сбой
                # питания не оставит вместо счёта пустой файл.
                stream.flush()
                os.fsync(stream.fileno())
            # S3: `mkstemp` создаёт файл с правами 0600, а после `os.replace`
            # это права файла счётчиков; нужны обычные 0644.
            os.chmod(tmp, 0o644)
            os.replace(tmp, self._path)
        except BaseException:
            # S5: сбой после `mkstemp` — временный файл убираем; прежний файл
            # счётчиков цел, потому что `os.replace` не состоялся.
            try:
                os.unlink(tmp)
            except OSError:
                # S5: удалить не вышло — наружу всё равно уходит исходный
                # сбой, его причину и надо показать.
                pass
            raise

    def snapshot(self) -> Dict[str, Counts]:
        """Вернуть счёт всех картинок из одного чтения файла сейчас (S1, S2, S4, S5, S6, W1).

        Ключ — имя ровно как в файле, значение — `Counts` с обоими полями.
        Нет файла, файл не читается (например, нет прав) или битый — пустой
        словарь, и файл не трогается. Для любого имени
        `snapshot().get(name, Counts(0, 0))` — то же, что `get(name)`.
        Список картинок берёт один снимок на запрос (W1): чтение файла на
        каждую картинку при тысяче картинок заняло бы почти секунду.
        """
        # Без замка: `increment` подменяет файл одним `os.replace`, поэтому
        # чтение видит целиком либо старый файл, либо новый (S3). С замком
        # опрос списка ждал бы чужой `fsync`.
        try:
            data = self._read()
        except OSError:
            # S1: файла нет (`FileNotFoundError`) — счёт ещё не начинался.
            # S5: прочие сбои чтения — тоже ноль; снимок только показывает
            # счёт и ничего не чинит.
            return {}
        if data is None:
            # S4: битый файл — ноль у всех, и файл не трогается: снимок
            # только показывает счёт, а откладывает битый файл `increment`,
            # которому есть что записать.
            return {}
        # S6: ключ — имя как есть, без нормализации Unicode: та же строка,
        # что отдаёт `scan` и по которой ищет `find` (F7). Имя в NFC и то же
        # имя в NFD — разные ключи. Регистр и пробелы по краям — тоже как
        # есть: APFS не различает регистр, но `Logo.jpg` и `logo.jpg` для
        # счёта — разные имена, и переименование одним регистром — с нуля.
        # S1: недостающее поле записи — 0.
        return {key: Counts(**_full(record)) for key, record in data.items()}

    def get(self, name: str) -> Counts:
        """Вернуть счёт картинки `name` по файлу, прочитанному сейчас (S1, S2, S4, S5, S6).

        Нет файла, записи или поля — ноль. Файл есть, но не читается
        (например, нет прав) или битый — тоже ноль, и файл не трогается.
        `name` ищется в файле ровно как есть, без нормализации Unicode.
        """
        # W1: одно правило чтения на `get` и снимок — список картинок и
        # `get` не могут разойтись ни в одном случае S1–S6.
        # S1: записи нет — ноль.
        return self.snapshot().get(name, Counts(0, 0))

    def increment(self, name: str, field: str) -> Counts:
        """Прибавить 1 к полю `field` картинки `name` и вернуть новый счёт (S1, S3, S4, S5, S6).

        `field` — одно из `FIELDS`. Файл читается заново; битый файл
        откладывается в `BROKEN_FILE`, и счёт идёт с пустого. Каждая запись
        дополняется до обоих полей, файл заменяется атомарно. Любой сбой
        файловой системы, кроме отсутствия файла счётчиков, —
        `StatsWriteError` с причиной; прежний файл при этом цел.
        """
        # S1: поле проверяется до любой работы с файлом — ошибка вызова не
        # должна превратиться в `StatsWriteError` из-за состояния диска.
        if field not in FIELDS:
            raise ValueError(f"unknown field: {field}")
        # S3: чтение, прибавление и запись — под одним замком, иначе два
        # потока прочтут одно значение и одна прибавка пропадёт.
        with self._lock:
            try:
                try:
                    data = self._read()
                except FileNotFoundError:
                    # S1: файла ещё нет — счёт с пустого, файл создаст запись
                    # ниже. Только отсутствие файла: нечитаемый файл (S5)
                    # счёт с нуля стёр бы накопленное.
                    data = {}
                if data is None:
                    # S4: битый файл не удаляется, а переименовывается рядом —
                    # накопленный счёт можно вернуть руками; `os.replace`
                    # заменяет прежнюю отложенную копию. Сбой переименования
                    # уходит в `StatsWriteError` ниже (S5): считать с пустого
                    # без отложенной копии значило бы затереть битый файл.
                    os.replace(self._path, self._folder / BROKEN_FILE)
                    # S4: счёт с пустого — из битого файла не переносится
                    # ничего, даже правильные записи.
                    data = {}
                # § 4.2: каждая запись пишется с обоими полями, поэтому после
                # записи файл в описанном формате, даже если его правили руками.
                # Чужих полей в допустимом файле нет (S4), и дополнение ничего
                # не выбрасывает.
                data = {key: _full(record) for key, record in data.items()}
                # S6: ключ — `name` ровно как есть, как и в `get`.
                record = data.setdefault(name, _full({}))
                record[field] += 1
                self._write(data)
            except OSError as exc:
                # S5: чтение, переименование битого файла, `mkstemp`, запись,
                # `fsync`, `chmod`, `replace` — наружу уходит только причина,
                # её покажет страница.
                # `strerror` пуст у `OSError`, созданного с одним текстом, —
                # тогда причина и есть этот текст.
                raise StatsWriteError(exc.strerror or str(exc)) from exc
        return Counts(**record)
