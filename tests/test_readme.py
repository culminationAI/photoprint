def _script_messages(path: Path) -> List[Tuple[str, str]]:
    """Строки, которые скрипт `path` печатает заказчику: пары (источник, текст).

    § 4.7, § 4.8: все тексты установщика и ярлыка печатает `echo` с одной
    строкой в двойных кавычках. Каждая команда `echo` в скрипте обязана
    разобраться: иначе её текст выпал бы из проверки молча. Переменная bash
    (`${STEP}`, `${F}`) становится подстановкой `{STEP}`, `{F}`.
    """
    text = path.read_text(encoding="utf-8")
    lines = ECHO_LINE.findall(text)
    # Нет ни одной строки — разбор сломан, проверять нечего.
    assert lines, path
    # Команда `echo` другого вида (одинарные кавычки, экранированная
    # кавычка, перенаправление) не попала бы в `lines`.
    assert len(ECHO_COMMAND.findall(text)) == len(lines), path
    # Доработка контролёра: `echo` или `printf` не в начале строки кода —
    # `[ … ] || echo "…"`, `{ echo "…"; exit 1; }`, `printf '…'` — тоже
    # печатает заказчику, а ECHO_COMMAND её не видит. Строка кода с такой
    # командой в любом месте обязана быть строкой ECHO_LINE. Комментарии
    # `#` не код: их текст заказчик не видит.
    unparsed = [
        line
        for line in text.splitlines()
        if not line.lstrip().startswith(SHELL_COMMENT)
        and PRINT_COMMAND.search(line)
        and not ECHO_LINE.match(line)
    ]
    assert unparsed == [], path
    messages: List[Tuple[str, str]] = []
    for line in lines:
        message = SHELL_VARIABLE.sub(lambda m: "{" + (m.group(1) or m.group(2)) + "}", line)
        messages.append((f"{path.name}: {line}", message))
    return messages


def _page_messages() -> List[Tuple[str, str]]:
    """Тексты ошибок страницы из PAGE_MESSAGES: пары (источник, текст).

    Каждый текст берётся из его определения в `index.html` — строки
    `const ИМЯ = "…";` или `const ИМЯ = (…) => `…`;` с начала строки файла
    (test_page закрепляет эти определения дословно). Определение ровно
    одно: второе, в том числе в комментарии, сделало бы выбор неоднозначным.
    Подстановка `${status}` становится `{status}`.
    """
    text = PAGE.read_text(encoding="utf-8")
    messages: List[Tuple[str, str]] = []
    for name in PAGE_MESSAGES:
        pattern = re.compile(
            r"^const " + name + r' = (?:"([^"]*)"|\([\w, ]*\) => `([^`]*)`);$', re.M
        )
        found = pattern.findall(text)
        assert len(found) == 1, name
        plain, template = found[0]
        message = plain or JS_VARIABLE.sub(r"{\1}", template)
        messages.append((f"index.html {name}", message))
    return messages


