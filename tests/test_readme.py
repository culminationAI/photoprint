def test_resolution_does_not_change_print(tmp_path: Path) -> None:
    """«Требования к картинкам» (задача 3.4a): поле «Разрешение» на печать не влияет, и числа README о миллиметрах верны.

    README велит задавать размер в пикселях и обещает, что поле
    «Разрешение» (dpi) на печать не влияет — можно поставить 203. Это
    обещание о клиенте, поэтому оно проверено печатью: одни и те же точки
    576×200 (серый переход — дизеринг P1 тоже участвует), сохранённые с
    каждым разрешением из RESOLUTIONS, пригодны (F3) и дают принтеру одни и
    те же байты — через `print_image` настоящего `UsbPrinter`, у которого
    подменены только `_open` и `_find` (§ 7.3). Разрешение в файлах и правда
    разное — иначе проверка ничего бы не доказала.

    Числа README о миллиметрах — арифметика редактора (мм / 25,4 × dpi с
    округлением до точки): 72 мм при 203 — 575 точек, отказ F3 п. 4; при
    203,2 — ровно HEAD_DOTS; 576 точек — 72 мм ленты, по 8 точек на мм.
    """
    pixels = Image.linear_gradient("L").resize((HEAD_DOTS, 200))
    outputs = []
    for dpi in RESOLUTIONS:
        path = tmp_path / f"dpi-{dpi}.jpg"
        pixels.save(path, "JPEG", quality=95, dpi=(dpi, dpi))
        with Image.open(path) as saved:
            assert tuple(round(value) for value in saved.info["dpi"]) == (dpi, dpi)
        assert check(path) is None
        printer = DummyUsbPrinter(BUNDLED)
        printer.print_image(load_printable(path))
        assert len(printer.opened) == 1
        outputs.append(printer.opened[0].output)
    assert outputs[0]
    assert outputs == [outputs[0]] * len(outputs)

    assert round(72 / MM_PER_INCH * 203) == 575
    assert round(72 / MM_PER_INCH * 203.2) == HEAD_DOTS
    assert HEAD_DOTS / 8 == 72
