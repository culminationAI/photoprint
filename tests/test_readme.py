def _squash(text: str) -> str:
    """Сжать каждый промежуток из пробелов и переносов строк в один пробел.

    README — разметка Markdown: длинное сообщение в абзаце может быть
    перенесено на другую строку, и заказчик увидит его целым. Поэтому
    сравнение не зависит от переносов строк, а сами слова и знаки — дословно.
    """
    return re.sub(r"\s+", " ", text).strip()


