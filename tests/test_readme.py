    rename = f"Файл `{JFIF}` — это JPEG: переименуйте его, заменив концовку на `{RENAME_TO}`"
    assert rename in hidden[0]
    # Контролёр (ворота 3.1): совет переименовать — только для JFIF, хвост
    # пункта целиком; прочие примеры встречаются в пункте ровно по разу —
