def _page_texts() -> Dict[str, str]:
    """Все тексты скрипта страницы: имя константы → текст, подстановка `${x}` → `{x}`.

    Доработка контролёра к задаче 3.1: каждая строка кода скрипта с русской
    буквой обязана быть определением PAGE_CONST. Тогда русский текст не
    спрячется ни в константе с переносом строки, ни прямо в коде
    (`el.textContent = "…"`), и test_page_texts_are_listed увидит любой
    новый текст страницы. Комментарии `/* … */` и `// …` вырезаются: их
    оператор не видит. Скрипт на странице один.
    """
    scripts = PAGE_SCRIPT.findall(PAGE.read_text(encoding="utf-8"))
    assert len(scripts) == 1
    code = BLOCK_COMMENT.sub("", scripts[0])
    texts: Dict[str, str] = {}
    stray = []
    for line in code.splitlines():
        if line.lstrip().startswith(LINE_COMMENT) or not CYRILLIC.search(line):
            continue
        match = PAGE_CONST.match(line)
        if not match:
            stray.append(line)
            continue
        name, plain, template = match.groups()
        assert name not in texts, name
        texts[name] = plain or JS_VARIABLE.sub(r"{\1}", template)
    assert stray == []
    return texts


