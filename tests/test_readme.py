def _quotes(text: str) -> List[str]:
    """Цитаты «…» верхнего уровня в тексте Markdown, пробелы сжаты (`_squash`).

    Вложенные «ёлочки» остаются внутри цитаты: сообщение «Готово. … «Печать
    картинок». …» — одна цитата. Непарная «ёлочка» роняет тест: цитата
    съела бы остаток документа или потерялась бы.
    """
    quotes: List[str] = []
    depth = 0
    start = 0
    for index, char in enumerate(text):
        if char == QUOTE_OPEN:
            if depth == 0:
                start = index + 1
            depth += 1
        elif char == QUOTE_CLOSE:
            assert depth > 0, text[max(0, index - 60) : index + 1]
            depth -= 1
            if depth == 0:
                quotes.append(_squash(text[start:index]))
    assert depth == 0
    return quotes


def _quote_matches(quote: str, message: str) -> bool:
    """Может ли цитата `quote` быть куском сообщения `message` таким, каким его видит заказчик.

    - «…» цитаты — вставка: закрывает любой кусок сообщения, в том числе
      подстановки и знак «…» самого сообщения («▸ скачивание…»);
    - подстановка `{имя}` сообщения совпадает с частью цитаты, только если
      имя есть в QUOTE_VALUES и часть подходит под его шаблон целиком
      («напечатано: 1», «а это PNG», путь «/Users/…/Desktop/…»);
    - остальные знаки цитаты совпадают со знаками сообщения дословно.
    Цитата — подстрока: начинается на границе знака или подстановки
    сообщения и кончается где угодно. Перебор идёт по парам (позиция в
    цитате, позиция в сообщении), каждая пара — один раз.
    """
    # Знаки сообщения; подстановка — кортеж из её имени.
    tokens: List[object] = []
    position = 0
    for match in PLACEHOLDER.finditer(message):
        tokens.extend(message[position : match.start()])
        tokens.append((match.group()[1:-1],))
        position = match.end()
    tokens.extend(message[position:])
    pending = [(0, start) for start in range(len(tokens) + 1)]
    seen = set(pending)
    while pending:
        at, to = pending.pop()
        if at == len(quote):
            return True
        steps = []
        if quote[at] == ELLIPSIS:
            # Вставка кончилась или закрывает ещё один знак сообщения.
            steps.append((at + 1, to))
            if to < len(tokens):
                steps.append((at, to + 1))
        elif to < len(tokens):
            token = tokens[to]
            if isinstance(token, tuple):
                value = QUOTE_VALUES.get(token[0])
                if value is not None:
                    steps.extend(
                        (end, to + 1)
                        for end in range(at + 1, len(quote) + 1)
                        if value.fullmatch(quote[at:end])
                    )
            elif token == quote[at]:
                steps.append((at + 1, to + 1))
        for step in steps:
            if step not in seen:
                seen.add(step)
                pending.append(step)
    return False


def _checklist_items() -> List[str]:
    """Пункты чек-листа `## N. …` как есть, с переносами строк: от заголовка пункта до следующего."""
    text = CHECKLIST.read_text(encoding="utf-8")
    heads = [match.start() for match in CHECK_ITEM.finditer(text)]
    return [text[start:end] for start, end in zip(heads, heads[1:] + [len(text)])]


def _todo_steps(item: str) -> Dict[int, str]:
    """Шаги «Что сделать» пункта чек-листа: номер → текст шага, пробелы сжаты.

    Шаг — от своей строки `N. ` до строки следующего шага или до «Что
    должно получиться»: блок кода с командой внутри шага остаётся в нём.
    """
    todo = item[item.index(TO_DO) + len(TO_DO) : item.index(EXPECTED)]
    marks = list(CHECK_STEP.finditer(todo))
    bounds = [match.start() for match in marks] + [len(todo)]
    return {
        int(match.group(1)): _squash(todo[start:end])
        for match, start, end in zip(marks, bounds, bounds[1:])
    }


def _sections(text: str) -> Dict[str, List[str]]:
    """Разделы документа Markdown: строка заголовка → строки раздела, начиная с самого заголовка.

    Раздел идёт до следующего заголовка того же или более высокого уровня:
    раздел `##` включает свои абзацы `###`. Строки внутри блока кода не
    заголовки. Заголовки не повторяются — иначе поиск раздела по
    заголовку был бы неоднозначным.
    """
    lines = text.splitlines()
    heads: List[Tuple[int, int]] = []
    in_code = False
    for index, line in enumerate(lines):
        if line.strip().startswith(FENCE):
            in_code = not in_code
            continue
        match = HEADING.match(line)
        if match and not in_code:
            heads.append((index, len(match.group(1))))
    sections: Dict[str, List[str]] = {}
    for number, (start, level) in enumerate(heads):
        end = next((index for index, deeper in heads[number + 1 :] if deeper <= level), len(lines))
        sections[lines[start]] = lines[start:end]
    assert len(sections) == len(heads), "заголовки повторяются"
    return sections


def _section(sections: Dict[str, List[str]], prefix: str) -> List[str]:
    """Строки единственного раздела, заголовок которого — `prefix` целиком или `prefix` и пробел.

    Продолжение после пробела разрешено: у абзаца «Разрешение на
    подключение принтера» в заголовке ещё «(MacBook с Apple silicon)».
    Раздела нет или их два — тест падает с этим заголовком в отчёте.
    """
    found = [head for head in sections if head == prefix or head.startswith(prefix + " ")]
    assert len(found) == 1, prefix
    return sections[found[0]]


def _list_items(lines: List[str]) -> List[str]:
    """Пункты списков верхнего уровня в строках раздела, пробелы сжаты (`_squash`).

    Пункт — от строки LIST_ITEM до пустой строки или начала следующего
    пункта; строки с отступом после него — его продолжение (перенос или
    вложенный список). Так длинный пункт, перенесённый на другую строку,
    остаётся одним пунктом, и его факты не расходятся по двум.
    """
    items: List[List[str]] = []
    current: List[str] = []
    for line in lines:
        if LIST_ITEM.match(line):
            current = [line]
            items.append(current)
        elif current and line[:1].isspace() and line.strip():
            current.append(line)
        else:
            current = []
    return [_squash("\n".join(item)) for item in items]


def _table_rows() -> List[Tuple[str, str]]:
    """Строки таблиц раздела «Если что-то не так» из двух ячеек: пары (сообщение, что делать).

    Пробелы в ячейках сжаты (`_squash`). Разделитель `|---|---|`
    пропускается; пустая ячейка «что делать» остаётся пустой строкой, и
    такую строку тест таблицы не засчитывает. Таблицы вне раздела не
    считаются: заказчик ищет своё сообщение там, куда его отправляет
    раздел «Установка».
    """
    rows: List[Tuple[str, str]] = []
    for line in _section(_sections(_readme()), TROUBLE):
        match = TABLE_ROW.match(line)
        if not match:
            continue
        cells = [_squash(cell) for cell in match.group(1).split("|")]
        if len(cells) == 2 and not set(cells[0]) <= set("-: "):
            rows.append((cells[0], cells[1]))
    return rows


