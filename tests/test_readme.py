def _assert_frame_and_text(image: Image.Image) -> None:
    """Проверить картинку приёмки: чёрная рамка по всем четырём краям и надпись внутри (чек-лист п. 2).

    `image` — точки режима `1` или серый режим `L`: 0 — чёрное, 255 —
    белое. Полоса FRAME_STRIP точек у каждого края вся чёрная; поле дальше
    TEXT_MARGIN точек от краёв, где рамки нет, — надпись: в нём есть и
    чёрное, и белое. Отчёт падения называет край, где рамки нет.
    """
    width, height = image.size
    for box in (
        (0, 0, width, FRAME_STRIP),
        (0, height - FRAME_STRIP, width, height),
        (0, 0, FRAME_STRIP, height),
        (width - FRAME_STRIP, 0, width, height),
    ):
        assert image.crop(box).getextrema() == (0, 0), box
    field = (TEXT_MARGIN, TEXT_MARGIN, width - TEXT_MARGIN, height - TEXT_MARGIN)
    assert image.crop(field).getextrema() == (0, 255)


def test_quotes_are_client_texts() -> None:
    """Доработка контролёра к задаче 3.1: каждая цитата «…» README и чек-листа — кусок текста клиента.

    Заказчик сверяет с цитатой то, что видит на экране. Правка текста в коде
    без правки документа молча развела бы их: например, чек-лист ждал бы
    «Принтер не ответил. …» после того, как текст стал другим. Поэтому
    каждая цитата верхнего уровня (`_quotes`) из `README.md` и
    `docs/acceptance.md` — одно из трёх:
    - кусок текста клиента (`_client_texts`: сообщения модулей, строки
      установщика и ярлыка с шагами «▸ …», тексты страницы, полные тексты
      непригодной картинки) — `_quote_matches`: «…» цитаты — вставка,
      числа, формат и путь стоят на месте подстановок QUOTE_VALUES; путь
      кончается перед точкой, и текст после него снова сверяется с
      сообщением (круг 2: иначе хвост цитаты после пути не проверялся);
    - название раздела своего документа («Если что-то не так», «Бумага
      кончилась») — целиком или до скобки заголовка;
    - надпись из QUOTE_NOT_CLIENT (кнопки и пункты macOS, надпись на
      картинке приёмки).
    Каждое исключение QUOTE_NOT_CLIENT встречается и само не текст
    клиента: лишнее спрятало бы будущую разошедшуюся цитату. Отчёт
    перечисляет все незнакомые цитаты сразу.
    """
    texts = _client_texts()
    unknown = []
    used = set()
    for path in (README, CHECKLIST):
        text = path.read_text(encoding="utf-8")
        titles = [HEADING.sub("", head) for head in _sections(text)]
        for quote in dict.fromkeys(_quotes(text)):
            if any(_quote_matches(quote, message) for message in texts):
                continue
            if any(title == quote or title.startswith(quote + " (") for title in titles):
                continue
            if quote in QUOTE_NOT_CLIENT:
                used.add(quote)
                continue
            unknown.append(f"{path.name}: «{quote}»")
    assert unknown == []
    assert sorted(used) == sorted(QUOTE_NOT_CLIENT)


